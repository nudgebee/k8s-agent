#!/usr/bin/env python3
"""Rewrite config/rbac/role.yaml from the chart.

Kubernetes refuses to let the operator grant a permission it does not hold, so its
role is: manage every kind the chart renders, plus every rule the chart grants.
Run after `helm dependency build charts/nudgebee-agent`.
"""

import pathlib
import subprocess

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
CHART = ROOT / "charts" / "nudgebee-agent"
OUT = ROOT / "operator" / "config" / "rbac" / "role.yaml"

APIS = ["security.openshift.io/v1/SecurityContextConstraints", "monitoring.coreos.com/v1"]
VARIANTS = [
    {"runner.readOnly": "true"},
    {"runner.readOnly": "false"},
    {"runner.readOnly": "false", "runner.enableWritePermissions": "true"},
]
COMMON = {"openshift.enabled": "true", "openshift.createScc": "true", "openshift.createPrivilegedScc": "true"}
MANAGE = ["create", "delete", "get", "list", "patch", "update", "watch"]


def plural(kind):
    name = kind.lower()
    if name.endswith("s"):
        return name if name.endswith("constraints") else name + "es"
    return name[:-1] + "ies" if name.endswith("y") else name + "s"


def render(values):
    cmd = ["helm", "template", "nudgebee-agent", str(CHART)]
    cmd += [arg for api in APIS for arg in ("--api-versions", api)]
    cmd += [arg for key, value in values.items() for arg in ("--set", f"{key}={value}")]
    return [doc for doc in yaml.safe_load_all(subprocess.check_output(cmd)) if doc]


def main():
    kinds, granted = {}, []
    for variant in VARIANTS:
        for doc in render({**COMMON, **variant}):
            group = doc["apiVersion"].rpartition("/")[0]
            kinds.setdefault(group, set()).add(plural(doc["kind"]))
            if doc["kind"] in ("Role", "ClusterRole"):
                granted += [rule for rule in doc.get("rules") or [] if rule not in granted]
    # Helm keeps release state in Secrets; the operator records events and status.
    kinds.setdefault("", set()).update({"secrets", "events"})
    rules = [{"apiGroups": [""], "resources": ["namespaces"], "verbs": ["get"]}]
    rules += [{"apiGroups": [g], "resources": sorted(r), "verbs": MANAGE} for g, r in sorted(kinds.items())]
    own = ["nudgebeeagents", "nudgebeeagents/status", "nudgebeeagents/finalizers"]
    rules.append({"apiGroups": ["agent.nudgebee.com"], "resources": own, "verbs": MANAGE})
    rules += granted
    role = {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRole",
            "metadata": {"name": "manager-role"}, "rules": rules}
    OUT.write_text("# Generated by operator/hack/gen-rbac.py. Do not edit.\n" + yaml.safe_dump(role, sort_keys=False))
    print(f"{len(rules)} rules; kinds: {sorted(k for v in kinds.values() for k in v)}")


if __name__ == "__main__":
    main()
